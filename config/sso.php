<?php

return [
    /*
    |--------------------------------------------------------------------------
    | Middle Platform (IdP) URL
    |--------------------------------------------------------------------------
    |
    | 中台 SSO 服務的對外 URL。本系統會把使用者導到 {middle_platform_url}/sso/login/
    | 進行登入,登入後中台會 redirect 回 {APP_URL}/sso/callback?token=<JWT>。
    |
    */
    'middle_platform_url' => env('MIDDLE_PLATFORM_URL', 'http://localhost'),

    /*
    |--------------------------------------------------------------------------
    | SSO JWT 驗證演算法
    |--------------------------------------------------------------------------
    |
    | 跟中台 SIMPLE_JWT.ALGORITHM 一致。
    |   - HS256(legacy):共用 jwt_secret
    |   - RS256(推薦):透過 jwks_url 從中台拉公鑰本地驗章
    |
    */
    'jwt_algorithm' => env('SSO_JWT_ALGORITHM', 'HS256'),

    /*
    |--------------------------------------------------------------------------
    | SSO JWT 驗證密鑰 (HS256 才用)
    |--------------------------------------------------------------------------
    |
    | RS256 模式下這個值被忽略。HS256 模式必須跟中台 DJANGO_SECRET_KEY 完全一致。
    |
    */
    'jwt_secret' => env('SSO_JWT_SECRET', env('APP_KEY')),

    /*
    |--------------------------------------------------------------------------
    | JWKS 公鑰來源 (RS256 才用)
    |--------------------------------------------------------------------------
    |
    | 中台 /.well-known/jwks.json 的完整 URL。
    | 範例:http://middle-platform:8000/.well-known/jwks.json
    |
    */
    'jwks_url' => env('SSO_JWKS_URL'),

    /*
    |--------------------------------------------------------------------------
    | JWKS 本地 cache TTL (秒)
    |--------------------------------------------------------------------------
    |
    | 公鑰拿到後 cache 這麼久,避免每次驗章都打中台。
    | 中台金鑰輪替時,驗章失敗會自動 flush 重抓,所以 TTL 可拉長。
    |
    */
    'jwks_cache_ttl' => env('SSO_JWKS_CACHE_TTL', 3600),
];
